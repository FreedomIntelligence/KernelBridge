"""Finite ports implemented by the worker, with no provider or publication authority."""
from __future__ import annotations

from collections.abc import Mapping
from contextlib import AbstractContextManager
from pathlib import Path
from typing import Any, Protocol

from kernelcat_executor.contracts.models import Action, Json, Outcome, Task
from kernelcat_executor.contracts.ports import Tool

from kernelcat_ingestion.plans import Asset, Element, Snapshot, SourcePlan, SourceSpec


class BoundEffects(Protocol):
    def execute(self, action: Action) -> Outcome: ...
    def snapshot(self) -> Json: ...
    def task_lock(self, task_id: str) -> AbstractContextManager[None]: ...


class EffectBinding(Protocol):
    def bind(self, task: Task, tools: list[Tool], *, credits: int,
             resource_limits: dict[str, int], runtime_digest: str) -> BoundEffects: ...


class EvidenceStore(Protocol):
    """Only immutable source/evidence operations; worker translates storage errors."""
    def capture(self, identity: Mapping[str, Any], content: bytes) -> dict[str, Any]: ...
    def source(self, source_id: str) -> dict[str, Any]: ...
    def read_source(self, source_id: str) -> bytes: ...
    def register_evidence(self, record: Mapping[str, Any]) -> None: ...
    def evidence(self, evidence_id: str) -> dict[str, Any] | None: ...


class EvidencePort(Protocol):
    @property
    def identity(self) -> str: ...
    def capture(self, spec: SourceSpec, asset: Asset, content: bytes, origin: str) -> Snapshot: ...
    def read(self, snapshot: Snapshot) -> bytes: ...
    def register_element(self, snapshot: Snapshot, element: Element) -> None: ...
    def check(self, snapshot: Snapshot, elements: tuple[Element, ...]) -> None: ...


class IngestionCommands(Protocol):
    def initialize(self, root: Path) -> None: ...
    def collect(self, state: Path, evidence_root: Path, plan: SourcePlan, *,
                authorize_network: bool) -> Json: ...
