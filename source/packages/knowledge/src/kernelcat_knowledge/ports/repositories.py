"""Protocol-only ports used by the transport-neutral application services."""
from __future__ import annotations

from collections.abc import Mapping
from typing import Any, Protocol


class CardReadRepository(Protocol):
    @property
    def active_index_revision(self) -> str: ...
    def cards_for_projection(self) -> tuple[list[dict[str, Any]], list[str]]: ...


class TrajectoryRepository(Protocol):
    def read(self, delta_id: str) -> Mapping[str, Any] | None: ...
    def write_atomic(self, delta_id: str, canonical_payload: str) -> None: ...


class SourceRepository(Protocol):
    def read(self, source_id: str) -> Mapping[str, Any] | None: ...
    def list_records(self) -> list[Mapping[str, Any]]: ...
    def write_atomic(self, source_id: str, canonical_payload: str) -> None: ...


class ArtifactResolver(Protocol):
    def read_bytes(self, ref: str) -> bytes: ...
    def store_contract(self, digest: str, canonical_payload: str) -> str: ...


class SourceContentReader(Protocol):
    def inspect_source(self, record: Mapping[str, Any]) -> Mapping[str, Any]: ...


class ReviewQueueRepository(Protocol):
    def write_atomic(self, review_id: str, canonical_payload: str) -> str: ...


class IndexReadModel(Protocol):
    active_index_revision: str
    load_errors: list[str]
    def load_all(self) -> list[dict[str, Any]]: ...
    def load_all_revisions(self) -> list[dict[str, Any]]: ...
    def find_by_id(self, knowledge_id: str) -> dict[str, Any] | None: ...
    def invalidate(self) -> None: ...


class PageReaderPort(Protocol):
    def get_pages(self, ids: list[str], *, follow_sources: bool = False, body_only: bool = False, max_chars: int | None = None) -> dict[str, Any]: ...


class RawReaderPort(Protocol):
    def grep(self, pattern: str, scope: str | None = None, context: int = 4, glob: str | None = None, include_tests: bool = False, max_hits: int = 30) -> dict[str, Any]: ...
    def read(self, path: str, start: int = 1, end: int | None = None) -> dict[str, Any]: ...
