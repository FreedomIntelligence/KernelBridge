"""Generate embedded application schemas from the reviewed JSON contracts."""
import hashlib
import json
from pathlib import Path
import pprint

root = Path(__file__).resolve().parents[1]
for name in ("application-host", "acceptance-evidence"):
    path = root / "contracts/execution/v1" / (name + ".schema.json")
    raw = path.read_bytes()
    schema = json.loads(raw)
    output = root / "packages/executor/src/kernelcat_executor/generated" / (name.replace("-", "_") + ".py")
    output.write_text('"""Generated by source/scripts/generate_application_contracts.py."""\n'
        + 'SCHEMA_SHA256 = ' + repr(hashlib.sha256(raw).hexdigest()) + '\n'
        + 'SCHEMA = ' + pprint.pformat(schema, sort_dicts=False) + '\n')
