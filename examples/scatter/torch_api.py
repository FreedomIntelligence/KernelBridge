"""Values-only torch_scatter-compatible finite-domain max/min using PyTorch.

This portable implementation is a selectable comparator, not an Ascend kernel
speed claim. Native Ascend candidates are generated by ascend_sources.py.
"""
import torch


def scatter(src, index, dim=-1, out=None, dim_size=None, reduce='max'):
    if reduce not in ('max', 'min'): raise ValueError('supported reductions: max, min')
    if not src.ndim or not -src.ndim <= dim < src.ndim: raise ValueError('invalid dim')
    if index.dtype != torch.long or index.device != src.device: raise ValueError('index must be int64 on src device')
    if src.dtype == torch.bool or src.is_complex(): raise ValueError('real numeric tensors required')
    if src.is_floating_point() and not torch.isfinite(src).all(): raise ValueError('finite-input contract')
    dim %= src.ndim
    if index.ndim == 1:
        index = index.reshape([1] * dim + [index.numel()] + [1] * (src.ndim - dim - 1))
    else:
        index = index.reshape(list(index.shape) + [1] * (src.ndim - index.ndim))
    index = index.expand_as(src)
    if dim_size is not None and (type(dim_size) is not int or dim_size < 0): raise ValueError('invalid dim_size')
    size = out.shape[dim] if out is not None else dim_size if dim_size is not None else int(index.max()) + 1 if index.numel() else 0
    if index.numel() and (int(index.min()) < 0 or int(index.max()) >= size): raise ValueError('index out of bounds')
    shape = list(src.shape); shape[dim] = size
    if out is not None:
        if list(out.shape) != shape or out.dtype != src.dtype or out.device != src.device: raise ValueError('invalid out')
        result = out.contiguous()
    else:
        info = torch.finfo(src.dtype) if src.is_floating_point() else torch.iinfo(src.dtype)
        sentinel = info.min if reduce == 'max' else info.max
        result = torch.full(shape, sentinel, device=src.device, dtype=src.dtype)
    result.scatter_reduce_(dim, index, src, reduce='amax' if reduce == 'max' else 'amin', include_self=True)
    if out is None: result.masked_fill_(result == sentinel, 0)
    return result


def scatter_max(src, index, dim=-1, out=None, dim_size=None):
    return scatter(src, index, dim, out, dim_size, 'max')


def scatter_min(src, index, dim=-1, out=None, dim_size=None):
    return scatter(src, index, dim, out, dim_size, 'min')
